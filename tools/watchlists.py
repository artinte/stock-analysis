def contains(name_or_symbol: str) -> bool:
    """判断股票名称或股票代码是否存在于股票池。"""
    value = name_or_symbol.strip().upper()

    for stocks in WATCHLISTS.values():
        if any(name.upper() == value for name in stocks):
            return True

        if any(code.upper() == value for code in stocks.values()):
            return True

    return False


def all_symbols() -> list[str]:
    """
    获取股票池中的全部股票代码。

    如果股票属于多个分类，只返回一次。
    """
    return list(
        dict.fromkeys(
            code for stocks in WATCHLISTS.values() for code in stocks.values()
        )
    )


def all_names() -> list[str]:
    """
    获取股票池中的全部股票名称。

    如果股票属于多个分类，只返回一次。
    """
    return list(
        dict.fromkeys(name for stocks in WATCHLISTS.values() for name in stocks)
    )


def all_stocks() -> dict[str, str]:
    """
    获取股票池中的全部唯一股票。

    如果股票属于多个分类，只保留一条记录。
    """
    return {
        name: code for stocks in WATCHLISTS.values() for name, code in stocks.items()
    }


def count() -> int:
    """
    获取股票池中的唯一股票数量。
    """
    return len(all_symbols())
